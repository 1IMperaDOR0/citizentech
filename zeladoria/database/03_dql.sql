-- (1) Duas tabelas com INNER JOIN: contexto territorial dos problemas.
SELECT o.ID_OCORRENCIA, o.DESCRICAO, o.STATUS, b.NOME AS BAIRRO
FROM GS_OCORRENCIA o
INNER JOIN GS_BAIRRO b ON b.ID_BAIRRO=o.ID_BAIRRO
WHERE o.ATIVA=1
ORDER BY o.ID_OCORRENCIA;

-- (2) Duas tabelas, INNER JOIN e agregação: demanda por categoria.
SELECT c.ID_CATEGORIA, c.NOME, COUNT(o.ID_OCORRENCIA) AS TOTAL_OCORRENCIAS
FROM GS_CATEGORIA c
INNER JOIN GS_OCORRENCIA o ON o.ID_CATEGORIA=c.ID_CATEGORIA
WHERE o.ATIVA=1
GROUP BY c.ID_CATEGORIA,c.NOME
ORDER BY TOTAL_OCORRENCIAS DESC,c.NOME;

-- (3) Duas tabelas, LEFT OUTER JOIN + WHERE + ORDER BY.
-- Mostra apenas ocorrências recebidas ativas, inclusive sem ordem (linha 6 da carga).
SELECT o.ID_OCORRENCIA,o.DESCRICAO,o.STATUS,s.ID_ORDEM,s.EQUIPE
FROM GS_OCORRENCIA o
LEFT OUTER JOIN GS_ORDEM_SERVICO s ON s.ID_OCORRENCIA=o.ID_OCORRENCIA
WHERE o.STATUS='RECEBIDO' AND o.ATIVA=1
ORDER BY o.CRIADA_EM,o.ID_OCORRENCIA;
