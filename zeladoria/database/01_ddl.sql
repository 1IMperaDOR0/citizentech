-- Oracle 12c+; executar em schema acadêmico vazio, nesta ordem: 01, 02, 03.
-- IDs gerados começam em 1000; carga didática reserva 1..999.
CREATE TABLE GS_BAIRRO (
  ID_BAIRRO NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) CONSTRAINT PK_GS_BAIRRO PRIMARY KEY,
  NOME VARCHAR2(100 CHAR) NOT NULL,
  CIDADE VARCHAR2(100 CHAR) NOT NULL,
  UF CHAR(2 CHAR) NOT NULL,
  CONSTRAINT UK_GS_BAIRRO UNIQUE (NOME,CIDADE,UF)
);

CREATE TABLE GS_CATEGORIA (
  ID_CATEGORIA NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) CONSTRAINT PK_GS_CATEGORIA PRIMARY KEY,
  NOME VARCHAR2(80 CHAR) NOT NULL CONSTRAINT UK_GS_CATEGORIA UNIQUE
);

CREATE TABLE GS_CIDADAO (
  ID_CIDADAO NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) CONSTRAINT PK_GS_CIDADAO PRIMARY KEY,
  NOME VARCHAR2(120 CHAR) NOT NULL,
  EMAIL VARCHAR2(180 CHAR) NOT NULL CONSTRAINT UK_GS_EMAIL UNIQUE
);

CREATE TABLE GS_OCORRENCIA (
  ID_OCORRENCIA NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) CONSTRAINT PK_GS_OCORRENCIA PRIMARY KEY,
  ID_BAIRRO NUMBER(19) NOT NULL,
  ID_CATEGORIA NUMBER(19) NOT NULL,
  DESCRICAO VARCHAR2(1000 CHAR) NOT NULL,
  LATITUDE NUMBER(9,6) NOT NULL,
  LONGITUDE NUMBER(9,6) NOT NULL,
  BLOQUEIO_TOTAL NUMBER(1) DEFAULT 0 NOT NULL,
  PROXIMO_HOSPITAL NUMBER(1) DEFAULT 0 NOT NULL,
  PROXIMO_ESCOLA NUMBER(1) DEFAULT 0 NOT NULL,
  STATUS VARCHAR2(20 CHAR) DEFAULT 'RECEBIDO' NOT NULL,
  CRIADA_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  ATIVA NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT FK_GS_O_BAIRRO FOREIGN KEY (ID_BAIRRO) REFERENCES GS_BAIRRO(ID_BAIRRO),
  CONSTRAINT FK_GS_O_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES GS_CATEGORIA(ID_CATEGORIA),
  CONSTRAINT CK_GS_LAT CHECK (LATITUDE BETWEEN -90 AND 90),
  CONSTRAINT CK_GS_LON CHECK (LONGITUDE BETWEEN -180 AND 180),
  CONSTRAINT CK_GS_BLOQUEIO CHECK (BLOQUEIO_TOTAL IN (0,1)),
  CONSTRAINT CK_GS_HOSPITAL CHECK (PROXIMO_HOSPITAL IN (0,1)),
  CONSTRAINT CK_GS_ESCOLA CHECK (PROXIMO_ESCOLA IN (0,1)),
  CONSTRAINT CK_GS_ATIVA CHECK (ATIVA IN (0,1)),
  CONSTRAINT CK_GS_STATUS CHECK (STATUS IN ('RECEBIDO','EM_ANALISE','EM_MANUTENCAO','CONCLUIDO'))
);

CREATE TABLE GS_RELATO (
  ID_RELATO NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) CONSTRAINT PK_GS_RELATO PRIMARY KEY,
  ID_OCORRENCIA NUMBER(19) NOT NULL,
  ID_CIDADAO NUMBER(19) NOT NULL,
  DESCRICAO VARCHAR2(1000 CHAR) NOT NULL,
  FOTO_URL VARCHAR2(500 CHAR) NOT NULL,
  CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT FK_GS_R_OCORRENCIA FOREIGN KEY (ID_OCORRENCIA) REFERENCES GS_OCORRENCIA(ID_OCORRENCIA),
  CONSTRAINT FK_GS_R_CIDADAO FOREIGN KEY (ID_CIDADAO) REFERENCES GS_CIDADAO(ID_CIDADAO)
);

CREATE TABLE GS_ORDEM_SERVICO (
  ID_ORDEM NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) CONSTRAINT PK_GS_ORDEM PRIMARY KEY,
  ID_OCORRENCIA NUMBER(19) NOT NULL CONSTRAINT UK_GS_ORDEM_OC UNIQUE,
  EQUIPE VARCHAR2(100 CHAR) NOT NULL,
  ABERTA_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONCLUIDA_EM TIMESTAMP,
  CONSTRAINT FK_GS_OS_OCORRENCIA FOREIGN KEY (ID_OCORRENCIA) REFERENCES GS_OCORRENCIA(ID_OCORRENCIA),
  CONSTRAINT CK_GS_OS_DATAS CHECK (CONCLUIDA_EM IS NULL OR CONCLUIDA_EM>=ABERTA_EM)
);

CREATE TABLE GS_HISTORICO_STATUS (
  ID_HISTORICO NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) CONSTRAINT PK_GS_HISTORICO PRIMARY KEY,
  ID_OCORRENCIA NUMBER(19) NOT NULL,
  STATUS_ANTERIOR VARCHAR2(20 CHAR),
  STATUS_NOVO VARCHAR2(20 CHAR) NOT NULL,
  RESPONSAVEL VARCHAR2(120 CHAR) NOT NULL,
  OBSERVACAO VARCHAR2(500 CHAR) NOT NULL,
  ALTERADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT FK_GS_H_OCORRENCIA FOREIGN KEY (ID_OCORRENCIA) REFERENCES GS_OCORRENCIA(ID_OCORRENCIA),
  CONSTRAINT CK_GS_H_ANTERIOR CHECK (STATUS_ANTERIOR IN ('RECEBIDO','EM_ANALISE','EM_MANUTENCAO','CONCLUIDO')),
  CONSTRAINT CK_GS_H_NOVO CHECK (STATUS_NOVO IN ('RECEBIDO','EM_ANALISE','EM_MANUTENCAO','CONCLUIDO'))
);

CREATE INDEX IX_GS_O_BAIRRO ON GS_OCORRENCIA(ID_BAIRRO);
CREATE INDEX IX_GS_O_CATEGORIA ON GS_OCORRENCIA(ID_CATEGORIA);
CREATE INDEX IX_GS_R_OCORRENCIA ON GS_RELATO(ID_OCORRENCIA);
CREATE INDEX IX_GS_R_CIDADAO ON GS_RELATO(ID_CIDADAO);
CREATE INDEX IX_GS_H_OCORRENCIA ON GS_HISTORICO_STATUS(ID_OCORRENCIA);
